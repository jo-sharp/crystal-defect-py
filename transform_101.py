import re
import math


#file to apply a shift to the coordinate section of a .cif file

#make the coordinate section only into its own little text file

#ask for name of text file here:

infilename=input("Enter name of text file not cif file: ")
print("Opening "+ infilename)

infile=open(infilename,"rt")

#make the filename of the output

outfilename=f"castepcell_{infilename}"

#open the output file for writing

outfile=open(outfilename,"wt")

print("Output file will be called "+ outfilename)

#Now go through the input file line by line doing things to it
#first define things that are always the same

#unit cell parameters
unita=7.3328
unitc=4.145
#supercell size in multiple of TiBe12 cell scm x scm x scm
scmx=4.0
scmy=1.0
scmz=8.0
#safety=0.277/(2*scmx)
#safety margin of half distance from twin plane to next layer of atoms to make it not a disaster when floats are rounded


newbeta=88.983

#new x' is old [10-1]
#new y' is old y
#new z' is old 2[103]
newcella=math.sqrt((unita**2)+(unitc**2))
newcellb=unita
newcellc=math.sqrt((4*(unita**2))+(36*(unitc**2)))
#define lengths of new cell


#xoffset=-newcella/4.0
#zoffset=newcellc/8.0

#bounds for finding z' coordinates in new cell
bottomz=1.0
topz=9.0
diffz=topz-bottomz

#bounds for finding x' coordinates in new cell
bottomx=-1.0
topx=3.0
diffx=topx-bottomx

#make cif file header with those cell parameters in
outfile.write('data_TiBe12_Wang2021\n')
outfile.write('_audit_creation_method         \'generated by Jo Sharp\'\n')
outfile.write(f'_cell_length_a                   {newcella:.6f}\n')
outfile.write(f'_cell_length_b                   {newcellb:.6f}\n')
outfile.write(f'_cell_length_c                   {newcellc:.6f}\n')
outfile.write(f'_cell_angle_alpha               90.000\n')
outfile.write(f'_cell_angle_beta               {newbeta:.6f}\n')
outfile.write(f'_cell_angle_gamma               90.000\n')
outfile.write('\n')
outfile.write('_symmetry_space_group_name_H-M     \'P 1\'\n')
outfile.write('\n')
outfile.write('loop_\n')
outfile.write('_symmetry_equiv_pos_as_xyz\n')
outfile.write('\'+x,+y,+z\'\n')
outfile.write('\n')


outfile.write('loop_\n')
outfile.write('_atom_site_label\n')
outfile.write('_atom_site_type_symbol\n')
outfile.write('_atom_site_occupancy\n')
outfile.write('_atom_site_fract_x\n')
outfile.write('_atom_site_fract_y\n')
outfile.write('_atom_site_fract_z\n')



for thisline in infile:
    #that already read the line

    #understand the line
    numberpattern=r'[0-9]\.[0-9]+'
    firstnumber=re.search(numberpattern,thisline)
    lastboring=firstnumber.start()-1
    #lastboring is the position in the line where the stuff that isn't numbers ends
    
    numbersection=re.findall(numberpattern,thisline)

    #print("Read a line \n")
    
    occupancy=numbersection[0]
    xcoord=float(numbersection[1])
    ycoord=float(numbersection[2])
    zcoord=float(numbersection[3])

    

#    print(f"Occupancy is {occupancy}\n")
#    print(f"xcoord is {str(xcoord)}\n")
#    print(f"ycoord is {str(ycoord)}\n")
#    print(f"zcoord is {str(zcoord)}\n")

#find out where they are between the two sides of the unit cell
    checkz=(4.0*xcoord)+(8.0*zcoord)
    checkx=(12.0*xcoord)-(8.0*zcoord)

    
    #loop for z'
    if checkz >= bottomz and checkz < topz:
      newz = (checkz-bottomz)/diffz
      #print(f'new zcoord is {newz}\n')
      
      #now loop for x'
      
      if checkx >= bottomx and checkx < topx:
        newx=(checkx-bottomx)/diffx

        #print(f'new xcoord is {newx}\n')
    
          #write new coords to file only if our atom is inside the cell in z', x' and y' intervals
        newlinestring=f"{thisline[0:lastboring]}  {occupancy}  {newx:.4f}  {ycoord:.4f}  {newz:.6f}\n"
        outfile.write(newlinestring)
        
        
      else:
        #print('New x out of range\n')
        continue  

    else:
      #print('New z out of range\n')
      continue


infile.close()
outfile.close()

