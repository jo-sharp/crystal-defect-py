import re
import math

#ask for stretch factor

stretchno=input("What integer stretch factor do you want to use?: ")
stretchfloat=float(stretchno)
stretchint=int(stretchno)
#could put something to check input is an integer but I don't care yet


#ask for name of text file here:

infilename=input("Enter name of text file not cif file: ")
print("Opening "+ infilename)

infile=open(infilename,"rt")

#make the filename of the output

outfilename=f"grown{stretchno}{infilename}"

#open the output file for writing

outfile=open(outfilename,"wt")

print("Output file will be called "+ outfilename)

#Now go through the input file line by line doing things to it
#first define things that are always the same

#unit cell parameters
unita=7.3328
unitc=4.145
#supercell size in multiple of TiBe12 cell scm x scm x scm
#scmx=6.0
#scmy=1.0
#scmz=10.0
#safety=0.277/(2*scmx)
#safety margin of half distance from twin plane to next layer of atoms to make it not a disaster when floats are rounded


cella=math.sqrt((unita**2)+(unitc**2))
cellb=unita
cellc=math.sqrt((4*(unita**2))+(36*(unitc**2)))
stretchedc=cellc*stretchfloat

#make cif file header with those cell parameters in
outfile.write('data_TiBe12_Wang2021\n')
outfile.write('_audit_creation_method         \'generated by Jo Sharp\'\n')
outfile.write(f'_cell_length_a                   {cella:.6f}\n')
outfile.write(f'_cell_length_b                   {cellb:.6f}\n')
outfile.write(f'_cell_length_c                   {stretchedc:.6f}\n')
outfile.write('_cell_angle_alpha               90.000000\n')
outfile.write('_cell_angle_beta               88.983\n')
outfile.write('_cell_angle_gamma               90.000000\n')
outfile.write('\n')
outfile.write('_symmetry_space_group_name_H-M     \'P 1\'\n')
outfile.write('\n')
outfile.write('loop_\n')
outfile.write('_symmetry_equiv_pos_as_xyz\n')
outfile.write('\'+x,+y,+z\'\n')
outfile.write('\n')


outfile.write('loop_\n')
outfile.write('_atom_site_label\n')
outfile.write('_atom_site_type_symbol\n')
outfile.write('_atom_site_occupancy\n')
outfile.write('_atom_site_fract_x\n')
outfile.write('_atom_site_fract_y\n')
outfile.write('_atom_site_fract_z\n')

#ok time for some atoms!


for thisline in infile:
    #that already read the line
    
    #read the alphanumeric bits
    #atom name is like Be[1-11 numbers or underscores]
    atomname_pattern='[A-Z{1}][a-z{0,1}][0-9_]{1,11}'
    atomnamearr=re.findall(atomname_pattern,thisline)
    atomname=atomnamearr[0]

    #atom symbol is 1-2 letters
    atsym_pattern='  [A-Z{1}][a-z{0,1}]'
    atomsymbolarr=re.findall(atsym_pattern,thisline)
    atomsymbol=atomsymbolarr[0]

    #understand the line
    numberpattern=r'[0-9]\.[0-9]+'
    firstnumber=re.search(numberpattern,thisline)
    lastboring=firstnumber.start()-1
    #lastboring is the position in the line where the stuff that isn't numbers ends


    
    numbersection=re.findall(numberpattern,thisline)

    #print("Read a line \n")
    
    #add something to parse the names
    occupancy=numbersection[0]
    xcoord=abs(float(numbersection[1]))
    ycoord=abs(float(numbersection[2]))
    zcoord=abs(float(numbersection[3]))
    
    #bit of quick maths to make loops run quicker
    llimit=(2*stretchint)
    quarstretch=stretchint*4
    
    if zcoord < 0.25:
    
    #section for if atom is in first quarter of cell outside twin
    #put atom down at its adjusted position
    #loop to make stretchno-1 copies of it at the right positions and label them atomname_stretchno

      for n in range(0,stretchint,1):
        newz1=(zcoord/stretchfloat)+(n/quarstretch)
        newatomname=atomname+'_'+str(n)
        newlinestring=f"{newatomname}{atomsymbol}  {occupancy}  {xcoord:.6f}  {ycoord:.6f}  {newz1:.6f}\n"
        #write its shifted position
        outfile.write(newlinestring)
    elif zcoord >= 0.25 and zcoord < 0.5:
    #section for if atom is in twin 0.25 to 0.5
    #we are replacing the ones from 0.5 to 0.75 with copies of this so ignore those
    #put atom down at adjusted positioon
    #loop to make (2*stretchno)-1 copies of it at right positions and label them atomname_loop index
      for m in range(0,llimit,1):
        newz2=((zcoord-0.25)/stretchfloat)+0.25+(m/quarstretch)
        newatomname=atomname+'_'+str(n)
        newlinestring=f"{newatomname}{atomsymbol}  {occupancy}  {xcoord:.6f}  {ycoord:.6f}  {newz2:.6f}\n"
        #write its shifted position
        outfile.write(newlinestring)
    elif zcoord >= 0.5 and zcoord < 0.75:
      continue
    elif zcoord >= 0.75:
    #section for if atom is in last quarter of cell outside twin
    #put atom down at adjusted position
    #loop to make stretchno-1 copies of it at the right positions and label them atomname_stretchno
      for p in range(0,stretchint,1):
        newz3=((zcoord-0.75)/stretchfloat)+0.75+(p/quarstretch)
        newatomname=atomname+'_'+str(n)
        newlinestring=f"{newatomname}{atomsymbol}  {occupancy}  {xcoord:.6f}  {ycoord:.6f}  {newz3:.6f}\n"
        #write its shifted position
        outfile.write(newlinestring)
    else:
      print("Mystery atom detected!\n")
      



infile.close()
outfile.close()

    #when we have got out of the for loop, close both files
